// ==========================================
// DISPLAY OPPORTUNITIES ON THE WEBSITE
// ==========================================

document.addEventListener("DOMContentLoaded", function () {

  const container =
    document.getElementById("opportunityList");

  if (!container) {
    return;
  }

  container.innerHTML = "";

  opportunities.forEach(function (opportunity) {

    const card =
      document.createElement("article");

    card.className = "card";

    card.dataset.category =
      opportunity.category;

    card.dataset.search = (
      opportunity.title + " " +
      opportunity.category + " " +
      opportunity.description + " " +
      opportunity.source
    ).toLowerCase();

    card.innerHTML = `
      <span class="tag">
        ${opportunity.tag}
      </span>

      <h3>
        ${opportunity.title}
      </h3>

      <p>
        ${opportunity.description}
      </p>

      <div class="deadline">
        Deadline: ${opportunity.deadline}
      </div>

      <div class="source">
        Official source: ${opportunity.source}
      </div>

      <a
        class="button"
        href="${opportunity.url}"
        target="_blank"
        rel="noopener noreferrer"
      >
        View Official Opportunity
      </a>
    `;

    container.appendChild(card);

  });

});
